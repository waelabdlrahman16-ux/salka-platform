#!/usr/bin/env node
// Regenerate src/components/Icon.tsx from @phosphor-icons/core.
//
//   npm i -D @phosphor-icons/core     # if it is not installed
//   npm run build:icons
//
// WHY GENERATE RATHER THAN IMPORT. @phosphor-icons/react would be the obvious
// choice, but it ships a React component per icon and this app already sits over
// Vite's bundle-size warning -- the page-weight work took the entry from 5,161 kB
// to 821 kB and it is not worth giving any of that back for 22 shapes. Inlining
// the path data keeps the runtime dependency at zero and the CDN request count
// at zero, which is what the previous Font Awesome file did too.
//
// TO ADD AN ICON: put it in MAP below with its Phosphor name, run this, commit
// the regenerated Icon.tsx. The script fails loudly if a name does not exist in
// both weights rather than silently emitting a broken glyph.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const A = 'node_modules/@phosphor-icons/core/assets'
const OUT = 'src/components/Icon.tsx'

// our name -> phosphor name. Two are deliberate reinterpretations, not renames:
