-- The compatibility backfill above intentionally leaves historical
-- staff-confirmed custom orders NULL. New orders, however, must begin with a
-- canonical quote state as soon as this migration is active.
create or replace function private.initialize_order_quote_state()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  -- A customer authenticated through Supabase Auth may not carry the legacy
  -- customer-session token. The public order wrapper has already established
  -- the authenticated subject in that case, so bind the new custom order to
  -- that account rather than making its history disappear from My Orders.
  if new.customer_id is null and new.order_type = 'custom_request' then
    new.customer_id := my_customer_id();
  end if;
  if new.quote_state is null then
    if new.order_type = 'catalog' then
      new.quote_state := 'not_required';
    elsif new.order_type = 'custom_request' then
      new.quote_state := 'pending';
    end if;
  end if;
  return new;
end;
$function$;

