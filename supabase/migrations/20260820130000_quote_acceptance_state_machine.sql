-- Quote acceptance state machine — complete local implementation draft.
--
-- LOCAL DRAFT: do not apply until its transition functions, RLS policies,
-- Edge Function changes, and test evidence have been reviewed together.
--
-- This migration is intentionally additive. It does not reinterpret legacy
-- pricing_status = 'confirmed' as customer consent and it does not change any
-- existing order's operational or payment state.

create table if not exists public.order_quotes (
  id bigint generated by default as identity primary key,
  order_id integer not null references public.orders(id) on delete restrict,
  version integer not null,
  state text not null,
  issued_by uuid references auth.users(id) on delete set null,
  issued_at timestamptz not null default now(),
  expires_at timestamptz not null,
  accepted_at timestamptz,
  accepted_by uuid references auth.users(id) on delete set null,
  rejected_at timestamptz,
  rejected_by uuid references auth.users(id) on delete set null,
  reminder_sent_at timestamptz,
  rejection_reason text,
  subtotal numeric not null check (subtotal >= 0),
  delivery_fee numeric not null check (delivery_fee >= 0),
  service_fee numeric not null default 0 check (service_fee >= 0),
  promo_code_id integer references public.promo_codes(id) on delete set null,
  promo_discount numeric not null default 0 check (promo_discount >= 0),
  promo_discount_service numeric not null default 0 check (promo_discount_service >= 0),
  promo_discount_delivery numeric not null default 0 check (promo_discount_delivery >= 0),
  promo_discount_vendor numeric not null default 0 check (promo_discount_vendor >= 0),
  wallet_used numeric not null default 0 check (wallet_used >= 0),
  total numeric not null check (total >= 0),
  payment_method text,
  deposit_required boolean not null default false,
  deposit_amount numeric not null default 0 check (deposit_amount >= 0),
  currency text not null default 'EGP' check (currency = 'EGP'),
  idempotency_key uuid not null,
  created_at timestamptz not null default now(),
  constraint order_quotes_state_check
    check (state in ('offered', 'accepted', 'rejected', 'expired', 'superseded')),
  constraint order_quotes_version_unique unique (order_id, version),
  constraint order_quotes_issue_idempotency_unique unique (order_id, idempotency_key),
  constraint order_quotes_expiry_after_issue check (expires_at > issued_at),
  constraint order_quotes_response_consistency check (
    (state = 'accepted' and accepted_at is not null
      and rejected_at is null and rejected_by is null)
    or (state = 'rejected' and rejected_at is not null
      and accepted_at is null and accepted_by is null)
    or (state in ('offered', 'expired', 'superseded')
      and accepted_at is null and accepted_by is null
      and rejected_at is null and rejected_by is null)
  ),
  constraint order_quotes_deposit_bound check (deposit_amount <= total)
);

