-- Issue only creates an offer. It deliberately does not update totals, payment
-- state, vendor visibility, dispatch state, wallet balances, or promo
-- redemptions on the live order.
create or replace function private.issue_custom_order_quote(
  p_order_id integer,
  p_subtotal numeric,
  p_expires_at timestamptz,
  p_idempotency_key uuid
)
returns json
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_order orders%rowtype;
  v_existing order_quotes%rowtype;
  v_snapshot record;
  v_quote_id bigint;
  v_version integer;
  v_expires_at timestamptz;
  v_superseded record;
begin
  if not is_supervisor() then raise exception 'not_authorized'; end if;
  if p_subtotal is null or p_subtotal < 0 then raise exception 'invalid_amount'; end if;
  if p_idempotency_key is null then raise exception 'invalid_idempotency_key'; end if;

  -- Policy is server-owned. The client still sends the intended value for
  -- request-shape compatibility, but it cannot lengthen or shorten the offer.
  v_expires_at := now() + interval '15 minutes';

  select * into v_order
    from orders
   where id = p_order_id and order_type = 'custom_request'
   for update;
  if not found then raise exception 'order_not_found'; end if;
  if v_order.status = 'Cancelled' then raise exception 'order_closed'; end if;
  if coalesce(v_order.quote_state,
       case when v_order.pricing_status = 'pending_quote' then 'pending' end) not in ('pending', 'offered', 'rejected', 'expired') then
    raise exception 'quote_not_pending';
  end if;

  -- A retry returns the original immutable offer; it never creates v2.
  select * into v_existing
    from order_quotes
   where order_id = p_order_id and idempotency_key = p_idempotency_key;
  if found then
    return json_build_object('quote_id', v_existing.id, 'version', v_existing.version, 'state', v_existing.state);
  end if;

  select * into v_snapshot from private.custom_order_quote_snapshot(p_order_id, p_subtotal);

  if not is_admin()
     and v_snapshot.total > private.setting_num('quote_admin_approval_ceiling_egp') then
    raise exception 'quote_requires_admin_approval';
  end if;

  -- A price that has not changed is not a new commercial offer. Returning the
  -- live version avoids resetting the customer's 15-minute decision window or
  -- emitting duplicate “price ready” notifications when staff retry a send.
  select * into v_existing
    from order_quotes
   where order_id = p_order_id and state = 'offered'
   for update;
  if found
     and v_existing.subtotal is not distinct from v_snapshot.subtotal
     and v_existing.delivery_fee is not distinct from v_snapshot.delivery_fee
     and v_existing.service_fee is not distinct from v_snapshot.service_fee
     and v_existing.promo_code_id is not distinct from v_snapshot.promo_code_id
     and v_existing.promo_discount is not distinct from v_snapshot.promo_discount
     and v_existing.promo_discount_service is not distinct from v_snapshot.promo_discount_service
     and v_existing.promo_discount_delivery is not distinct from v_snapshot.promo_discount_delivery
     and v_existing.promo_discount_vendor is not distinct from v_snapshot.promo_discount_vendor
     and v_existing.wallet_used is not distinct from v_snapshot.wallet_used
     and v_existing.total is not distinct from v_snapshot.total
     and v_existing.payment_method is not distinct from v_snapshot.payment_method
     and v_existing.deposit_required is not distinct from v_snapshot.deposit_required
     and v_existing.deposit_amount is not distinct from v_snapshot.deposit_amount then
    return json_build_object('quote_id', v_existing.id, 'version', v_existing.version, 'state', v_existing.state);
  end if;

  for v_superseded in
    update order_quotes
       set state = 'superseded'
     where order_id = p_order_id and state = 'offered'
     returning id
  loop
    perform private.record_order_event(
      p_order_id, 'quote.superseded', 'quote',
      jsonb_build_object('state', 'offered', 'quote_id', v_superseded.id),
      jsonb_build_object('state', 'superseded', 'quote_id', v_superseded.id),
      case when is_admin() then 'admin' else 'supervisor' end, null, p_idempotency_key
    );
  end loop;

  select coalesce(max(version), 0) + 1 into v_version
    from order_quotes where order_id = p_order_id;

  insert into order_quotes (
    order_id, version, state, issued_by, expires_at,
    subtotal, delivery_fee, service_fee, promo_code_id,
    promo_discount, promo_discount_service, promo_discount_delivery, promo_discount_vendor,
    wallet_used, total, payment_method, deposit_required, deposit_amount,
    idempotency_key
  ) values (
    p_order_id, v_version, 'offered', auth.uid(), v_expires_at,
    v_snapshot.subtotal, v_snapshot.delivery_fee, v_snapshot.service_fee, v_snapshot.promo_code_id,
    v_snapshot.promo_discount, v_snapshot.promo_discount_service,
    v_snapshot.promo_discount_delivery, v_snapshot.promo_discount_vendor,
    v_snapshot.wallet_used, v_snapshot.total, v_snapshot.payment_method,
    v_snapshot.deposit_required, v_snapshot.deposit_amount,
    p_idempotency_key
  ) returning id into v_quote_id;

  update orders
     set quote_state = 'offered', current_quote_id = v_quote_id
   where id = p_order_id;

  perform private.notify_quote_customer(
    p_order_id, v_quote_id, 'quote_offered', 'سالكة — سعر طلبك جاهز',
    'راجع السعر ووافق خلال 15 دقيقة عشان نبدأ طلبك'
  );

  insert into order_status_events (order_id, from_status, to_status, actor, actor_uid)
  values (p_order_id, 'quote:' || coalesce(v_order.quote_state, 'pending'), 'quote:offered',
          case when is_admin() then 'admin' else 'supervisor' end, auth.uid());
  perform private.record_order_event(
    p_order_id, 'quote.offered', 'quote', jsonb_build_object('state', coalesce(v_order.quote_state, 'pending')),
    jsonb_build_object('state', 'offered', 'quote_id', v_quote_id, 'version', v_version, 'expires_at', v_expires_at),
    case when is_admin() then 'admin' else 'supervisor' end, null, p_idempotency_key
  );

  return json_build_object('quote_id', v_quote_id, 'version', v_version, 'state', 'offered');
end;
$function$;

