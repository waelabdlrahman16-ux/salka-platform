-- No public table policies are added here. Quote reads and decisions must first
-- be routed through customer-authenticated database functions, which will be
-- introduced with the Edge Function implementation. Leaving the new table
-- default-deny prevents accidental client exposure while that work is pending.

-- Vendors previously read every order belonging to their restaurant, including
-- unpriced custom requests. Keep staff, supervisor, and driver visibility
-- unchanged, but let a vendor see a custom request only after its quote has
-- been accepted and any required payment is no longer pending. Historical
-- staff-confirmed custom orders intentionally retain quote_state NULL during
-- rollout, so their pre-existing visibility is preserved.
drop policy if exists "read orders" on public.orders;
create policy "read orders" on public.orders for select
  using (
    is_admin()
    or exists (select 1 from delivery_assignments da where da.order_id = orders.id and da.driver_id = my_driver_id())
    or supervisor_may_touch_order(id)
    or (
      restaurant_id = my_restaurant_id()
      and (
        order_type <> 'custom_request'
        or (quote_state is null and status <> 'awaiting_payment')
        or (quote_state = 'accepted' and status <> 'awaiting_payment')
      )
    )
  );

drop policy if exists "read order items" on public.order_items;
create policy "read order items" on public.order_items for select
  using (
    is_admin()
    or exists (select 1 from delivery_assignments da where da.order_id = order_items.order_id and da.driver_id = my_driver_id())
    or (is_supervisor() and exists (select 1 from orders o where o.id = order_items.order_id))
    or exists (
      select 1 from orders o
       where o.id = order_items.order_id
         and o.restaurant_id = my_restaurant_id()
         and (
           o.order_type <> 'custom_request'
           or (o.quote_state is null and o.status <> 'awaiting_payment')
           or (o.quote_state = 'accepted' and o.status <> 'awaiting_payment')
         )
    )
  );

-- Both customer history paths return JSON rather than generated table types.
-- Include the canonical quote state so a list never presents an offered quote
-- as a final total, while retaining the legacy pricing field for old clients.
create or replace function private.my_customer_orders()
returns json
language sql
stable
security definer
set search_path to 'public'
as $function$
  select coalesce(json_agg(row_to_json(x)), '[]'::json) from (
    select o.id, o.public_token, o.total, o.status, o.created_at,
           coalesce(o.pricing_status, 'n/a') as pricing_status,
           o.quote_state, r.name as restaurant_name
      from orders o join restaurants r on r.id = o.restaurant_id
     where o.customer_id = my_customer_id()
       and o.created_at > now() - interval '90 days'
     order by o.id desc limit 30
  ) x;
$function$;

create or replace function public.my_orders(
  p_phone text, p_session_token uuid, p_auth_user_id uuid
)
returns json
language plpgsql
security definer
set search_path to 'public'
as $function$
declare v_phone text;
begin
  if p_session_token is not null then
    select c.phone into v_phone
      from customer_sessions cs join customers c on c.id = cs.customer_id
     where cs.token = p_session_token and cs.expires_at > now();
  end if;
  if v_phone is null and p_auth_user_id is not null then
    select c.phone into v_phone from customers c
     where c.auth_user_id = p_auth_user_id and coalesce(c.phone, '') <> '' limit 1;
  end if;
  if v_phone is null then raise exception 'not_logged_in'; end if;
  v_phone := normalize_phone(v_phone);
  return (
    select coalesce(json_agg(row_to_json(x)), '[]'::json)
      from (
        select o.id, o.public_token, o.total, o.status, o.created_at,
               coalesce(o.pricing_status, 'n/a') as pricing_status,
               o.quote_state, r.name as restaurant_name
          from orders o join restaurants r on r.id = o.restaurant_id
         where normalize_phone(o.customer_phone) = v_phone
           and o.created_at > now() - interval '30 days'
         order by o.id desc limit 20
      ) x
  );
end;
$function$;

-- Pure quote calculator. Unlike private.reprice_order(), this function makes no
-- writes to orders, wallets, redemptions, or events. The issue transition will
-- call it while holding the order lock, then store its result as an immutable
-- quote snapshot. Acceptance—not quotation—is responsible for ledger effects.
create or replace function private.custom_order_quote_snapshot(
  p_order_id integer,
  p_subtotal numeric
)
returns table (
  subtotal numeric,
  delivery_fee numeric,
  service_fee numeric,
  promo_code_id integer,
  promo_discount numeric,
  promo_discount_service numeric,
  promo_discount_delivery numeric,
  promo_discount_vendor numeric,
  wallet_used numeric,
  total numeric,
  payment_method text,
  deposit_required boolean,
  deposit_amount numeric
)
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_order orders%rowtype;
  v_promo promo_codes%rowtype;
  v_service numeric;
  v_discount numeric := 0;
  v_discount_service numeric := 0;
  v_discount_delivery numeric := 0;
  v_discount_vendor numeric := 0;
  v_total numeric;
  v_wallet numeric;
  v_deposit numeric := 0;
begin
  if p_subtotal is null or p_subtotal < 0 then raise exception 'invalid_amount'; end if;

  select * into v_order
    from orders
   where id = p_order_id and order_type = 'custom_request';
  if not found then raise exception 'order_not_found'; end if;
  if v_order.status = 'Cancelled' then raise exception 'order_closed'; end if;

  v_service := round(p_subtotal * private.setting_num('service_fee_percent') / 100.0);

  if v_order.promo_code_id is not null then
    select * into v_promo from promo_codes where id = v_order.promo_code_id;
    if found then
      v_discount := private.promo_discount_for(
        v_promo, p_subtotal, coalesce(v_order.delivery_fee, 0), v_service);
      select cut_service, cut_delivery, cut_vendor
        into v_discount_service, v_discount_delivery, v_discount_vendor
        from private.promo_split(
          v_promo.applies_to, v_discount, coalesce(v_order.delivery_fee, 0), v_service);
    end if;
  end if;

  v_total := greatest(0, p_subtotal + coalesce(v_order.delivery_fee, 0) + v_service - v_discount);
  v_wallet := least(coalesce(v_order.wallet_used, 0), v_total);

  -- orders.total is the net amount due after any wallet contribution. The
  -- deposit threshold and amount must use that same net number.
  v_total := v_total - v_wallet;

  if v_order.payment_method = 'cod'
     and v_total > private.setting_num('cod_deposit_threshold_egp') then
    v_deposit := least(
      ceil(v_total * private.setting_num('cod_deposit_percent') / 100.0),
      v_total
    );
  end if;

  return query select
    p_subtotal,
    coalesce(v_order.delivery_fee, 0),
    v_service,
    v_order.promo_code_id::integer,
    v_discount,
    v_discount_service,
    v_discount_delivery,
    v_discount_vendor,
    v_wallet,
    v_total,
    v_order.payment_method,
    v_deposit > 0,
    v_deposit;
end;
$function$;

-- Customer push is issued by the server so it is delivered while the app is
-- backgrounded or the phone is locked. A failed push must never roll back the
-- quote transition itself.
create or replace function private.notify_quote_customer(
  p_order_id integer, p_quote_id bigint, p_kind text, p_title text, p_body text
)
returns void language plpgsql security definer set search_path to 'public' as $function$
declare v_token text; v_platform text; v_order_token uuid; v_secret text;
begin
  select push_token, coalesce(push_platform, 'web'), public_token
    into v_token, v_platform, v_order_token from orders where id = p_order_id;
  if v_token is null or v_order_token is null then return; end if;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name = 'push_webhook_secret';
  perform net.http_post(
    url := 'https://pqpnwxyevrsipklzmwex.supabase.co/functions/v1/send-push',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-webhook-secret', coalesce(v_secret, '')),
    body := jsonb_build_object(
      'tokens', jsonb_build_array(jsonb_build_object('token', v_token, 'platform', v_platform)),
      'title', p_title, 'body', p_body,
      'data', jsonb_build_object('order_id', p_order_id, 'quote_id', p_quote_id, 'kind', p_kind, 'link', '/track/' || v_order_token)
    )
  );
exception when others then
  return;
end;
$function$;

