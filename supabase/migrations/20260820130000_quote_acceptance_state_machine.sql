create or replace function private.expire_custom_order_quotes()
returns integer
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_expired_ids bigint[];
  v_count integer;
  v_quote record;
begin
  -- One reminder per quote, inside the final two minutes. The caller must run
  -- this sweep at least once per minute for the reminder window to be useful.
  for v_quote in
    update order_quotes
       set reminder_sent_at = now()
     where state = 'offered'
       and reminder_sent_at is null
       and expires_at > now()
       and expires_at <= now() + interval '2 minutes'
     returning id, order_id
  loop
    perform private.notify_quote_customer(
      v_quote.order_id, v_quote.id, 'quote_expiring', 'سالكة — العرض هينتهي قريب',
      'قدامك أقل من دقيقتين توافق على سعر طلبك'
    );
  end loop;

  with expired as (
    update order_quotes q
       set state = 'expired'
     where q.state = 'offered' and q.expires_at <= now()
     returning q.id, q.order_id
  )
  select array_agg(id), count(*) into v_expired_ids, v_count from expired;

  if coalesce(v_count, 0) = 0 then return 0; end if;

  update orders o
     set quote_state = 'expired'
   where o.current_quote_id = any(v_expired_ids)
     and o.quote_state = 'offered';

  insert into order_status_events (order_id, from_status, to_status, actor)
  select q.order_id, 'quote:offered', 'quote:expired', 'system'
    from order_quotes q where q.id = any(v_expired_ids);

  insert into order_events (order_id, event_type, state_dimension, before_state, after_state, actor_role)
  select q.order_id, 'quote.expired', 'quote',
         jsonb_build_object('state', 'offered', 'quote_id', q.id),
         jsonb_build_object('state', 'expired', 'quote_id', q.id), 'system'
    from order_quotes q where q.id = any(v_expired_ids);

  for v_quote in
    select id, order_id from order_quotes where id = any(v_expired_ids)
  loop
    perform private.notify_quote_customer(
      v_quote.order_id, v_quote.id, 'quote_expired', 'سالكة — انتهت صلاحية عرض السعر',
      'العرض انتهى. هنراجع طلبك ونبعتلك عرض جديد لو لسه محتاجه'
    );
  end loop;

  return v_count;
end;
$function$;

